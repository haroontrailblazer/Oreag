def render(spec: dict) -> str:
    if spec["otp_type"] is None:
        link_section = ""
        token_note = (
            "CODE ONLY: Supabase issues a bare nonce for reauthentication -\n"
            "  there is no {{ .TokenHash }} and no link to build."
        )
    else:
        link = _link(spec["otp_type"], spec["next_path"])
        link_section = LINK_SECTION.format(link=link, cta=spec["cta"])
        token_note = (
            f"Carries BOTH the {{{{ .Token }}}} code and a {{{{ .TokenHash }}}} "
            f"link (type={spec['otp_type']})."
        )
    return SHELL.format(
        dashboard_name=spec["dashboard_name"],
        subject=spec["subject"],
        preheader=spec["lead"],
        heading=spec["heading"],
        lead=spec["lead"],
        code_label=spec["code_label"],
        link_section=link_section,
        reassurance=spec["reassurance"],
        token_note=token_note,
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for filename, spec in TEMPLATES.items():
        (OUT / filename).write_text(render(spec), encoding="utf-8")
        print(f"wrote {filename}")


if __name__ == "__main__":
    main()
