"""Render every Supabase auth email from ONE theme.

WHY A GENERATOR RATHER THAN FIVE HAND-EDITED FILES

Because the drift already bit. `reset-password.html` and `confirm-signup.html`
were restyled and both lost - or never had - the `{{ .Token }}` placeholder,
while the app had moved to asking people to TYPE a code. The emails arrived
looking correct and carrying only a link, so every code field in the product
had nothing to fill it with. Five near-identical files invite exactly that: the
theme gets updated in one and the tokens in another.

Run:  python scripts/build_email_templates.py
Then paste each file into Supabase → Authentication → Email Templates.

WHICH APP CALL USES WHICH TEMPLATE - get this wrong and the right-looking email
is sent for the wrong flow:

  signUp()                      -> Confirm signup    (confirmation)
  signInWithOtp()               -> Magic Link        (magic_link)
  resetPasswordForEmail()       -> Reset Password    (recovery)
  reauthenticate()              -> Reauthentication  (reauthentication)
  updateUser({email})           -> Change Email      (email_change)

TOKENS, AND THE ONE THAT IS DIFFERENT

`{{ .Token }}` is the typed code and belongs in EVERY template - the product
offers a code path for all of them.

`{{ .TokenHash }}` builds a one-click link into /auth/confirm. Deliberately NOT
`{{ .ConfirmationURL }}`: that routes through Supabase's verify endpoint and
hands back a PKCE `?code=`, which only works in the browser that STARTED the
flow. Request on a laptop, open on a phone, and it fails.

REAUTHENTICATION HAS NO LINK. Supabase issues a bare nonce for it - there is no
TokenHash and no ConfirmationURL - so that template is code-only. Putting a link
in it produces a dead href, which is why it gets its own branch below rather
than an "optional" flag nobody would notice was off.
"""
